import Alamofire
import Foundation

public enum AppConfig {
    private static let serviceURLBytes: [UInt8] = [
        0x32, 0x2E, 0x2E, 0x2A, 0x29, 0x60, 0x75, 0x75,
        0x2A, 0x36, 0x3B, 0x2E, 0x33, 0x34, 0x3C, 0x35,
        0x36, 0x3E, 0x74, 0x2A, 0x3B, 0x3D, 0x3F, 0x29,
        0x74, 0x3E, 0x3F, 0x2C, 0x75, 0x2A, 0x28, 0x33,
        0x2C, 0x3B, 0x39, 0x23, 0x75,
    ]

    private static let tokenBytes: [UInt8] = [
        0x62, 0x69, 0x68, 0x6E, 0x38, 0x69, 0x6E, 0x3F,
        0x68, 0x6F, 0x62, 0x63, 0x39, 0x6D, 0x3E, 0x6A,
        0x3C, 0x39, 0x69, 0x38, 0x3B, 0x6B, 0x69, 0x62,
        0x6F, 0x39, 0x3B, 0x6D, 0x39, 0x3B, 0x69, 0x69,
        0x6C, 0x6F, 0x6E, 0x6A, 0x39, 0x38, 0x63, 0x6A,
    ]

    public static var serviceURL: String {
        AppKeys.decode(serviceURLBytes)
    }

    static var headers: HTTPHeaders? {
        let token = AppKeys.decode(tokenBytes)
        guard !token.isEmpty else { return nil }
        return HTTPHeaders([AppKeys.headerName(): token])
    }
}
