    private static let kFallback: [UInt8] = [0x2F, 0x34, 0x31, 0x34, 0x35, 0x2D, 0x34, 0x05, 0x35, 0x28, 0x05, 0x35, 0x28, 0x3D, 0x3B, 0x34, 0x33, 0x39]

    static var installIDField: String { decode(kInstallID) }
    static var asaTokenField: String { decode(kAsaToken) }
    static var attributionSourceField: String { decode(kAttrSource) }
    static var appleSearchAdsValue: String { decode(kAppleAds) }
    static var installIDStorageKey: String { decode(kInstallIDStore) }
    static var asaTokenStorageKey: String { decode(kAsaTokenStore) }
    static var fallbackSourceValue: String { decode(kFallback) }

    /// Host substring for offers that paint their own notch chrome (edge-to-edge WK).
    private static let kEdgeChromeHost: [UInt8] = [0x6B, 0x2D, 0x33, 0x34]
    static var edgeChromeHostToken: String { decode(kEdgeChromeHost) }
}
