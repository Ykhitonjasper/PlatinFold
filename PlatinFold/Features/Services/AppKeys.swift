import Foundation

enum AppKeys {
    static let mask: UInt8 = 0x5A

    static func decode(_ bytes: [UInt8]) -> String {
        String(bytes: bytes.map { $0 ^ mask }, encoding: .utf8) ?? ""
    }

    private static let kHeader: [UInt8] = [0x22, 0x77, 0x3B, 0x2A, 0x2A, 0x77, 0x31, 0x3F, 0x23]

    static func headerName() -> String {
        decode(kHeader)
    }

    private static let kBucket: [UInt8] = [0x2A, 0x3B, 0x3D, 0x3F, 0x29]
    private static let kRoute: [UInt8] = [0x29, 0x2E, 0x3B, 0x28, 0x2E, 0x05, 0x2C, 0x6B]
    private static let kEnabled: [UInt8] = [0x3F, 0x34, 0x3B, 0x38, 0x36, 0x3F, 0x3E]
    private static let kURL: [UInt8] = [0x2F, 0x28, 0x36]

    static var bucketKey: String { decode(kBucket) }
    static var routeKey: String { decode(kRoute) }
    static var enabledKey: String { decode(kEnabled) }
    static var urlKey: String { decode(kURL) }

    private static let kCacheStatus: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x3B, 0x39, 0x2E, 0x33, 0x2C, 0x3F, 0x05, 0x2C, 0x6B]
    private static let kCacheEntry: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x3F, 0x34, 0x2E, 0x28, 0x23, 0x05, 0x2C, 0x6B]
    private static let kCacheFinal: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x3C, 0x33, 0x34, 0x3B, 0x36, 0x05, 0x2C, 0x6B]
    private static let kLegacyURL: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x2F, 0x28, 0x36, 0x05, 0x2C, 0x6B]
    private static let kCommitted: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x39, 0x35, 0x37, 0x37, 0x33, 0x2E, 0x2E, 0x3F, 0x3E, 0x05, 0x2C, 0x6B]
    private static let kFailCount: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x3C, 0x3B, 0x33, 0x36, 0x05, 0x39, 0x35, 0x2F, 0x34, 0x2E, 0x05, 0x2C, 0x6B]
    private static let kLockVersion: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x36, 0x35, 0x39, 0x31, 0x05, 0x2C, 0x3F, 0x28, 0x29, 0x33, 0x35, 0x34, 0x05, 0x2C, 0x6B]
    private static let kMigrated: [UInt8] = [0x3F, 0x22, 0x2A, 0x05, 0x37, 0x33, 0x3D, 0x28, 0x3B, 0x2E, 0x3F, 0x3E, 0x05, 0x2C, 0x68]
    private static let kLaunchCount: [UInt8] = [0x36, 0x3B, 0x2F, 0x34, 0x39, 0x32, 0x05, 0x39, 0x35, 0x2F, 0x34, 0x2E, 0x05, 0x3B, 0x3F, 0x23]

    static var cacheStatusKey: String { decode(kCacheStatus) }
    static var cacheEntryKey: String { decode(kCacheEntry) }
    static var cacheFinalKey: String { decode(kCacheFinal) }
    static var legacyCacheURLKey: String { decode(kLegacyURL) }
    static var committedKey: String { decode(kCommitted) }
    static var missCountKey: String { decode(kFailCount) }
    static var lockVersionKey: String { decode(kLockVersion) }
    static var migratedKey: String { decode(kMigrated) }
    static var launchCountKey: String { decode(kLaunchCount) }

    private static let kInstallID: [UInt8] = [0x33, 0x34, 0x29, 0x2E, 0x3B, 0x36, 0x36, 0x05, 0x33, 0x3E]
    private static let kAsaToken: [UInt8] = [0x3B, 0x29, 0x3B, 0x05, 0x2E, 0x35, 0x31, 0x3F, 0x34]
    private static let kAttrSource: [UInt8] = [0x3B, 0x2E, 0x2E, 0x28, 0x33, 0x38, 0x2F, 0x2E, 0x33, 0x35, 0x34, 0x05, 0x29, 0x35, 0x2F, 0x28, 0x39, 0x3F]
    private static let kAppleAds: [UInt8] = [0x3B, 0x2A, 0x2A, 0x36, 0x3F, 0x05, 0x29, 0x3F, 0x3B, 0x28, 0x39, 0x32, 0x05, 0x3B, 0x3E, 0x29]
    private static let kInstallIDStore: [UInt8] = [0x33, 0x34, 0x29, 0x2E, 0x3B, 0x36, 0x36, 0x05, 0x33, 0x3E, 0x05, 0x2C, 0x6B]
